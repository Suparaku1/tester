public class ComparisonOperators {

    public static void main(String[] args) {

        double a = 4.0;
        long b = 4;

        boolean gt = a > b;
        System.out.println(gt);

        boolean gte = a >= b;
        System.out.println(gte);

        boolean lt = a < b;
        System.out.println(lt);

        boolean lte = a <= b;
        System.out.println(lte);

        boolean et = a == b;
        System.out.println(et);

        boolean net = a != b;
        System.out.println(net);

    }
}
