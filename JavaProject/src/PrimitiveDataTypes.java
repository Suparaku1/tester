public class PrimitiveDataTypes {

    public static void main(String[] args) {

        byte myFirstVariable; //declare a variable named myFirstVariable

        //initializing variable myFirstVariable with a value
        myFirstVariable = 34;

        //print the value of variable myFirstVariable
        System.out.println("myFirstVariable = " + myFirstVariable);
        //myFirstVariable = 34

        short sh = 1234;
        System.out.println("sh = " + sh);

        System.out.println("sum of sh and myFirstVariable is = " + (sh + myFirstVariable)); //1268

        int i = 76764334;
        System.out.println(i);

        long myLong = 4251267623343L;
        System.out.println(myLong);

        float fl = 1.23F;

        double d = 23.45678;

        char ch = 'a';

        boolean isRaining = true;

    }
}
